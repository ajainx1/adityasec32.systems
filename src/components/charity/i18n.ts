export const getTranslation = (arg1: string, arg2?: string): string => {
  const validLangs: Language[] = ['en', 'hi', 'es', 'fr', 'de', 'bn', 'ta', 'te', 'ja', 'ar'];
  let lang: Language = 'en';
  let key = '';

  if (validLangs.includes(arg1 as Language) && arg2) {
    lang = arg1 as Language;
    key = arg2;
  } else {
    key = arg1;
    if (arg2 && validLangs.includes(arg2 as Language)) {
      lang = arg2 as Language;
    }
  }

  return UI_TRANSLATIONS[lang]?.[key] || UI_TRANSLATIONS['en']?.[key] || key;
};
